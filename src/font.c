static const unsigned char *find_glyph(char c)
{
    unsigned int i;

    if (c >= 'a' && c <= 'z')
        c -= 32;

    for (i = 0; i < sizeof(glyphs) / sizeof(glyphs[0]); i++) {
        if (glyphs[i].c == c)
            return glyphs[i].rows;
    }

    return NULL;
}

float font_text_width(const char *text, float scale)
{
    float width = 0;

    while (*text) {
        width += 6.0f * scale;
        text++;
    }

    if (width > 0)
        width -= scale;

    return width;
}

void font_draw_text(
    const char *text,
    float x,
    float y,
    float scale,
    int r,
    int g,
    int b
)
{
    float cursor = x;

    while (*text) {
        const unsigned char *rows;
        int row;
        int col;

        if (*text == ' ') {
            cursor += 6.0f * scale;
            text++;
            continue;
        }

        rows = find_glyph(*text);

        if (rows) {
            for (row = 0; row < 7; row++) {
                for (col = 0; col < 5; col++) {
                    if (rows[row] & (1 << (4 - col))) {
                        renderer_rect(
                            cursor + col * scale,
                            y + row * scale,
                            scale,
                            scale,
                            r,
                            g,
                            b
                        );
                    }
                }
            }
        }

        cursor += 6.0f * scale;
        text++;
    }
}

void font_draw_centered(
    const char *text,
    float center_x,
    float y,
    float scale,
    int r,
    int g,
    int b
)
{
    font_draw_text(
        text,
        center_x - font_text_width(text, scale) / 2.0f,
        y,
        scale,
        r,
        g,
        b
    );
}
